# ========== FUNGSI SUPABASE + AUTO CREATE TABEL ==========
def sb_query(sql):
    try:
        url = f"{SUPABASE_URL}/rest/v1/rpc/exec_sql"
        headers = SB_HEADERS.copy()
        headers["Prefer"] = "params=single-object"
        r = requests.post(url, headers=headers, json={"sql": sql}, timeout=5)
        return r.status_code
    except: return 500

def auto_create_table():
    check = sb_select("orders", "select=id&limit=1")
    if isinstance(check, list):
        print("Tabel 'orders' sudah ada")
        return
    print("Tabel 'orders' tidak ada. Membuat otomatis...")
    sql = """
    create table if not exists public.orders (
      id bigint generated by default as identity primary key,
      order_id text,
      side text,
      price numeric,
      qty numeric,
      status text,
      created_at timestamp with time zone default now()
    );
    alter table public.orders disable row level security;
    """
    status = sb_query(sql)
    if status == 200:
        print("Tabel 'orders' berhasil dibuat + RLS dimatikan")
        send_telegram("✅ Tabel 'orders' di Supabase berhasil dibuat otomatis")

def sb_select(table, filters=""):
    try:
        url = f"{SUPABASE_URL}/rest/v1/{table}?{filters}"
        r = requests.get(url, headers=SB_HEADERS, timeout=5)
        return r.json() if r.status_code == 200 else []
    except Exception as e: return f"ERROR: {e}"

def sb_insert(table, data):
    try:
        url = f"{SUPABASE_URL}/rest/v1/{table}"
        requests.post(url, headers=SB_HEADERS, json=data, timeout=5)
    except Exception as e: print(f"SB INSERT ERROR: {e}")

def sb_delete(table, filters):
    try:
        url = f"{SUPABASE_URL}/rest/v1/{table}?{filters}"
        requests.delete(url, headers=SB_HEADERS, timeout=5)
    except Exception as e: print(f"SB DELETE ERROR: {e}")

