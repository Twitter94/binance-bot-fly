# ========== SATPAM BINANCE ==========
def get_binance_rules(symbol):
    global BINANCE_RULES
    r = requests.get(f"{BASE_URL}/api/v3/exchangeInfo?symbol={symbol}", timeout=5)
    info = r.json()['symbols'][0]
    for f in info['filters']:
        if f['filterType'] == 'MIN_NOTIONAL': BINANCE_RULES['min_notional'] = float(f['minNotional'])
        if f['filterType'] == 'LOT_SIZE':
            BINANCE_RULES['min_qty'] = float(f['minQty'])
            BINANCE_RULES['step_size'] = float(f['stepSize'])

def signed_request(method, path, params={}):
    params['timestamp'] = int(time.time() * 1000)
    query_string = urlencode(params)
    signature = hmac.new(BINANCE_SECRET.encode(), query_string.encode(), hashlib.sha256).hexdigest()
    headers = {'X-MBX-APIKEY': BINANCE_API_KEY}
    url = f"{BASE_URL}{path}?{query_string}&signature={signature}"
    return requests.request(method, url, headers=headers, timeout=5).json()

def get_price(): return float(requests.get(f"{BASE_URL}/api/v3/ticker/price?symbol={SYMBOL}", timeout=3).json()['price'])

# ========== KUNCI BARU: WAJIB SYNC DULU ==========
def wajib_sync_dulu():
    """KUNCI: Selalu sync Binance + Supabase sebelum action apapun"""
    print("[SYNC] Sinkronisasi 1 arah dari BINANCE...")
    sync_dan_cek(SYMBOL)
